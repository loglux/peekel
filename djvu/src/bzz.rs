//! BZZ, the general-purpose compressor of DjVu (Appendix 4 of the official DjVu v3 specification): the directory of a document, the
//! bookmarks, the annotations, the hidden text and the JB2 data of a page are all BZZ data. A Burrows-Wheeler transform, a
//! move-to-front table whose order is steered by a frequency estimate, and the Z'-Coder ([`crate::zp`]) for the numbers.
//!
//! A stream is blocks one after the other. A block is its size (24 bits, no contexts), the speed of the frequency estimate (two
//! bits), the move-to-front numbers of its symbols, and one end-of-block symbol among them whose place is what the inverse
//! transform starts from (spec 13.2.1.2, 13.2.1.3). The contexts of the Z'-Coder (260 are used) are not reset between blocks.
//!
//! Things the spec leaves open or gets wrong, and what is done here:
//! - how a stream of several blocks ends is not said. A block size of 0 ends it, and so does data that has run out before the size
//!   of the next block (a stream without that terminator); both are what the real files of the author's books do or allow.
//! - the pseudo-code of 13.2.1.2 has `freq[j] := freq[k-1]` where `freq[k]` is meant, and a muddled choice of the context for
//!   the first two numbers that 13.2.2.3 makes plain: context 0 or 1 when the previous number was 0 or 1, else 2.
//! - 13.2.2.3 says 262 contexts, the pseudo-code on page 65 says 260 and uses indices 0 to 259; 262 are made and 260 used.
//! - the block size is limited to 4 MiB (spec 13.1), and a block that does not hold exactly one end symbol is refused.

use crate::Error;
use crate::zp::ZpDecoder;

/// The largest block (spec 13.1: block sizes between 10K and 4M).
pub const MAX_BLOCK: usize = 4 * 1024 * 1024;

/// Contexts of the Z'-Coder: 262 as 13.2.2.3 says, of which the numbers decode touches 0 to 259.
const CONTEXTS: usize = 262;

/// Decodes a BZZ stream. `max_output` is the most it may produce (a stream is not trusted to say how big it is).
///
/// # Errors
/// [`Error::BadBzz`] for a stream that is cut, has a block size beyond the limit, a block that is not a valid transform, or more
/// output than `max_output`.
pub fn decode(data: &[u8], max_output: usize) -> Result<Vec<u8>, Error> {
    let mut zp = ZpDecoder::new(data);
    let mut contexts = [0_u8; CONTEXTS];
    let mut out = Vec::new();
    loop {
        if zp.is_exhausted() {
            break; // a stream that ends without the block size 0
        }
        let size = decode_raw(&mut zp, 24);
        if size == 0 {
            break;
        }
        if size > MAX_BLOCK {
            return Err(Error::BadBzz("a block bigger than the spec allows"));
        }
        decode_block(&mut zp, &mut contexts, size, max_output, &mut out)?;
    }
    Ok(out)
}

/// A `b`-bit number read without contexts (`decode_raw` of the spec).
fn decode_raw(zp: &mut ZpDecoder<'_>, bits: u32) -> usize {
    let mut n = 1_usize;
    while n < (1 << bits) {
        n = n * 2 + usize::from(zp.decode_pass_half());
    }
    n - (1 << bits)
}

/// A `bits`-bit number read with the contexts `offset` to `offset + 2^bits - 2` (`decode_bin` of the spec).
fn decode_bin(zp: &mut ZpDecoder<'_>, contexts: &mut [u8; CONTEXTS], offset: usize, bits: u32) -> usize {
    let mut n = 1_usize;
    while n < (1 << bits) {
        n = n * 2 + usize::from(zp.decode_bit(&mut contexts[offset + n - 1]));
    }
    n - (1 << bits)
}

/// One block (spec 13.2.1.2 and 13.2.1.3), its `size` already read; what it decodes to is added to `out`.
fn decode_block(
    zp: &mut ZpDecoder<'_>,
    contexts: &mut [u8; CONTEXTS],
    size: usize,
    max_output: usize,
    out: &mut Vec<u8>,
) -> Result<(), Error> {
    // phase 1: the numbers, and through them the symbols of the transformed block
    let fshift: u32 = if zp.decode_pass_half() {
        if zp.decode_pass_half() { 2 } else { 1 }
    } else {
        0
    };
    let mut mtf: [u8; 256] = std::array::from_fn(|i| i as u8);
    let mut data = vec![0_u8; size];
    let mut marker: Option<usize> = None;
    let mut mtfno = 3_usize;
    let mut fadd = 4_u32;
    let mut freq = [0_u32; 4];
    for (i, slot) in data.iter_mut().enumerate() {
        if zp.is_exhausted() {
            return Err(Error::BadBzz("the data ends inside a block"));
        }
        // the first bit's context: 0 or 1 after a number 0 or 1, else 2 (13.2.2.3)
        let ctxid = mtfno.min(2);
        mtfno = if zp.decode_bit(&mut contexts[ctxid]) {
            0
        } else if zp.decode_bit(&mut contexts[ctxid + 3]) {
            1
        } else if zp.decode_bit(&mut contexts[6]) {
            2 + decode_bin(zp, contexts, 7, 1)
        } else if zp.decode_bit(&mut contexts[8]) {
            4 + decode_bin(zp, contexts, 9, 2)
        } else if zp.decode_bit(&mut contexts[12]) {
            8 + decode_bin(zp, contexts, 13, 3)
        } else if zp.decode_bit(&mut contexts[20]) {
            16 + decode_bin(zp, contexts, 21, 4)
        } else if zp.decode_bit(&mut contexts[36]) {
            32 + decode_bin(zp, contexts, 37, 5)
        } else if zp.decode_bit(&mut contexts[68]) {
            64 + decode_bin(zp, contexts, 69, 6)
        } else if zp.decode_bit(&mut contexts[132]) {
            128 + decode_bin(zp, contexts, 133, 7)
        } else {
            256 // the end-of-block symbol
        };
        if mtfno == 256 {
            if marker.replace(i).is_some() {
                return Err(Error::BadBzz("more than one end-of-block symbol"));
            }
            *slot = 0;
            continue;
        }
        *slot = mtf[mtfno];
        // update the frequencies, then rotate the table
        fadd = fadd.saturating_add(fadd >> fshift);
        if fadd > 0x1000_0000 {
            fadd >>= 24;
            for f in &mut freq {
                *f >>= 24;
            }
        }
        let fc = if mtfno < 4 {
            fadd.saturating_add(freq[mtfno])
        } else {
            fadd
        };
        let mut k = mtfno;
        while k > 3 {
            mtf[k] = mtf[k - 1];
            k -= 1;
        }
        while k > 0 && fc >= freq[k - 1] {
            mtf[k] = mtf[k - 1];
            freq[k] = freq[k - 1]; // the spec prints freq[j] here
            k -= 1;
        }
        mtf[k] = *slot;
        freq[k] = fc;
    }

    // phase 2: the inverse Burrows-Wheeler transform
    let marker = marker
        .filter(|&m| m > 0 && m < size)
        .ok_or(Error::BadBzz("no valid end-of-block symbol"))?;
    let mut count = [0_u32; 256];
    let mut posn = vec![0_u32; size];
    for (i, &symbol) in data.iter().enumerate() {
        if i != marker {
            posn[i] = count[usize::from(symbol)];
            count[usize::from(symbol)] += 1;
        }
    }
    let mut last = 1_u32;
    for c in &mut count {
        let n = *c;
        *c = last;
        last += n;
    }
    if usize::try_from(last).ok() != Some(size) {
        return Err(Error::BadBzz("the symbol counts do not add up to the block"));
    }
    let posc = data.clone();
    let mut k = 0_usize;
    let mut at = size - 1;
    while at > 0 {
        at -= 1;
        let symbol = *posc
            .get(k)
            .ok_or(Error::BadBzz("the transform leads out of the block"))?;
        data[at] = symbol;
        let next = count[usize::from(symbol)]
            .checked_add(
                *posn
                    .get(k)
                    .ok_or(Error::BadBzz("the transform leads out of the block"))?,
            )
            .ok_or(Error::BadBzz("the transform leads out of the block"))?;
        k = usize::try_from(next).map_err(|_| Error::BadBzz("the transform leads out of the block"))?;
    }
    if k != marker {
        return Err(Error::BadBzz("the transform does not end at the end-of-block symbol"));
    }
    if out.len() + (size - 1) > max_output {
        return Err(Error::BadBzz("more output than the limit"));
    }
    out.extend_from_slice(&data[..size - 1]);
    Ok(())
}

